// npm run build:demo
// Builds the two example brains with the real code (fake Claude) and writes docs/data.js for the demo page.
import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { getConfig } from "../src/config.js";
import { buildBrain } from "../src/build.js";
import { ask } from "../src/ask.js";
import { askHandbook } from "../src/handbook.js";
import { analyse } from "../src/report.js";
import { degree } from "../src/graph.js";
import { renderNote } from "../src/vault.js";
import { readInbox } from "../src/docs.js";
import { loadLenses } from "../src/lenses.js";
import { BRAINS, loadExample, exampleRoot, fakeExtract, fakeAnswer } from "./examples.js";

const now = new Date("2026-10-31T09:00:00Z");
const today = "2026-10-31";
const out = { today, brains: {} };

for (const brain of BRAINS) {
  const { extractions, answers } = loadExample(brain);
  const root = exampleRoot(brain);
  const { graph: g } = await buildBrain({ root, config: { ...getConfig({}), root, defaultLens: brain }, extract: fakeExtract(extractions), now, log: () => {} });
  const deg = degree(g);
  const { docs } = readInbox(root);
  const a = analyse(g, today);
  const qa = [];
  for (const q of answers) {
    const r = brain === "handbook" ? await askHandbook(g, q.question, fakeAnswer(answers), { today, maxDays: 180 }) : await ask(g, q.question, fakeAnswer(answers));
    qa.push({ question: q.question, answer: r.answer, citations: r.citations, sources: r.sources, unknown: r.unknown, grounded: r.grounded, searched: r.notes.length, warnings: r.warnings || [] });
  }
  out.brains[brain] = {
    nodes: Object.values(g.nodes).map((n) => ({ id: n.id, name: n.name, type: n.type, summary: n.summary, date: n.date, value: n.value, aliases: n.aliases, sources: n.sources, degree: deg[n.id] || 0, markdown: renderNote(g, n) })),
    edges: g.edges,
    docs: docs.map((d) => ({
      id: d.id, name: d.name, title: d.title, text: d.text,
      original: g.docs[d.id].flags.length ? readFileSync(join(root, "inbox", d.id), "utf8") : null,
      ...g.docs[d.id],
    })),
    report: { hubs: a.hubs.map((n) => ({ id: n.id, name: n.name, type: n.type, links: n.links })), upcoming: a.upcoming.map((n) => ({ id: n.id, name: n.name, type: n.type, date: n.date })), review: a.review.length, flagged: a.flagged.map((d) => d.title), dropped: a.dropped, counts: a.counts, handbook: a.handbook, stale: a.stale, conflicts: a.conflicts, staleDays: a.staleDays },
    answers: qa,
  };
}
const lensDir = new URL("../lenses/", import.meta.url).pathname;
out.lenses = loadLenses(lensDir).map(({ id, name, folders, types, description, instructions }) => ({ id, name, folders, types, description, instructions }));
writeFileSync(new URL("../docs/data.js", import.meta.url), `// Generated by scripts/build-demo.js. Do not edit by hand.\nwindow.THREADLINE = ${JSON.stringify(out, null, 1)};\n`);
console.log(`Wrote docs/data.js: ${BRAINS.map((b) => `${b} ${out.brains[b].nodes.length} notes / ${out.brains[b].edges.length} links`).join(", ")}.`);
